"""Generate shared/crdt-vectors.json from the Python CRDT.

The same file is asserted by server/tests/test_crdt.py and
client/src/crdt.test.ts, so the Python and TypeScript implementations can't
quietly drift apart. Regenerate with:

    cd server && uv run python scripts/gen_vectors.py

Then re-run both test suites. If the TypeScript side starts failing, the two
implementations disagree and one of them is wrong.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

# Run as a script from server/, so put server/ on the path before importing app.
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from app.crdt import RGA  # noqa: E402

OUTPUT = Path(__file__).resolve().parents[2] / "shared" / "crdt-vectors.json"


def case(name: str, note: str, ops: list[dict[str, Any]]) -> dict[str, Any]:
    """Run `ops` through a fresh replica and record the text it must produce."""
    doc = RGA("vector-runner")
    for op in ops:
        doc.apply(op)
    return {"name": name, "note": note, "ops": ops, "text": doc.text}


def build() -> dict[str, Any]:
    cases: list[dict[str, Any]] = []

    alice = RGA("alice")
    cases.append(case("simple insert", "plain typing", alice.local_insert(0, "hello")))

    alice = RGA("alice")
    ops = alice.local_insert(0, "ab")
    ops += alice.local_insert(1, "c")
    cases.append(
        case("insert between neighbours", "forces newest-first sibling order", ops)
    )

    alice = RGA("alice")
    ops = alice.local_insert(0, "hello world")
    ops += alice.local_delete(5, 6)
    cases.append(case("delete a range", "tombstones stay as anchors", ops))

    alice, bob = RGA("alice"), RGA("bob")
    base = alice.local_insert(0, "hi")
    for op in base:
        bob.apply(op)
    ops = list(base) + alice.local_insert(2, "A") + bob.local_insert(2, "B")
    cases.append(
        case("concurrent insert at the same spot", "both survive, order is fixed", ops)
    )

    alice, bob = RGA("alice"), RGA("bob")
    base = alice.local_insert(0, "hi")
    for op in base:
        bob.apply(op)
    ops = list(base) + alice.local_insert(0, "oh ") + bob.local_insert(2, "!")
    cases.append(case("concurrent edits at different spots", "no conflict", ops))

    alice = RGA("alice")
    ops = alice.local_insert(0, "abc")
    cases.append(
        case("children before parents", "causal buffering", list(reversed(ops)))
    )

    alice = RGA("alice")
    inserts = alice.local_insert(0, "abc")
    deletes = alice.local_delete(1, 1)
    cases.append(case("delete before insert", "set-based tombstones", deletes + inserts))

    alice = RGA("alice")
    ops = alice.local_insert(0, "abc")
    ops = ops + ops  # every operation duplicated
    cases.append(case("duplicated operations", "idempotency", ops))

    alice, bob = RGA("alice"), RGA("bob")
    a_ops: list[dict[str, Any]] = []
    for char in "cba":
        a_ops += alice.local_insert(0, char)
    b_ops: list[dict[str, Any]] = []
    for char in "zyx":
        b_ops += bob.local_insert(0, char)
    cases.append(
        case(
            "backward typing interleaves",
            "known RGA limitation, pinned so both sides agree on it",
            a_ops + b_ops,
        )
    )

    return {
        "note": (
            "Generated by server/scripts/gen_vectors.py. Asserted by both "
            "server/tests/test_crdt.py and client/src/crdt.test.ts so the two "
            "implementations of the CRDT cannot drift apart."
        ),
        "cases": cases,
    }


if __name__ == "__main__":
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(json.dumps(build(), indent=2) + "\n")
    data = json.loads(OUTPUT.read_text())
    print(f"wrote {OUTPUT.relative_to(OUTPUT.parents[1])} — {len(data['cases'])} cases")
    for entry in data["cases"]:
        print(f"  {entry['name']:38} -> {entry['text']!r}")
